#!/usr/bin/env python3
"""DialogueManager.cs -> src/RogueCastle/Dialogue/DialogueData.h: every
m_dialogDict.Add("Name", new DialogueObj(speakers[], texts[])) as LOC ids.

    python3 tools/convert_dialogue.py ref/RogueLegacy1
"""
import re
import sys

ref = sys.argv[1] if len(sys.argv) > 1 else 'ref/RogueLegacy1'
src = open(ref + '/RogueCastle/src/Managers/DialogueManager.cs', encoding='utf-8-sig').read()
src = re.sub(r'//[^\n]*', '', src)
pat = re.compile(r'm_dialogDict\.Add\(\s*"([^"]+)"\s*,\s*new DialogueObj\(\s*new string\[\]\s*\{([^}]*)\}\s*,\s*new string\[\]\s*\{([^}]*)\}', re.S)
entries = []
for name, speakers, texts in pat.findall(src):
    s = re.findall(r'"([^"]*)"', speakers)
    t = re.findall(r'"([^"]*)"', texts)
    if len(s) != len(t):
        print('skipped', name, file=sys.stderr)
        continue
    entries.append((name, s, t))
out = ['// Generated by tools/convert_dialogue.py from DialogueManager.cs: do not edit.',
       '// Each dialogue: pages of (speaker LOC id, text LOC id).',
       '#pragma once', '', 'namespace RogueCastle', '{', 'namespace Dialogue', '{',
       '\tstruct Page { const char *speaker, *text; };',
       '\tstruct Entry { const char *name; int count; const Page *pages; };', '']
for i, (name, s, t) in enumerate(entries):
    out.append('\tconst Page PAGES_%d[] = { %s };' % (i, ', '.join('{ "%s", "%s" }' % p for p in zip(s, t))))
out.append('')
out.append('\tconst Entry ENTRIES[] = {')
for i, (name, s, t) in enumerate(entries):
    out.append('\t\t{ "%s", %d, PAGES_%d },' % (name, len(s), i))
out += ['\t};', '\tconst int ENTRY_COUNT = %d;' % len(entries), '}', '}', '']
import os
os.makedirs('src/RogueCastle/Dialogue', exist_ok=True)
open('src/RogueCastle/Dialogue/DialogueData.h', 'w', encoding='utf-8').write('\n'.join(out))
print(len(entries), 'dialogues')
