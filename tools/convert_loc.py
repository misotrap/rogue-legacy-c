#!/usr/bin/env python3
"""Translations: converts the game's LocStrings*.resx (in the reference
source) into assets/lang/<code>.txt ("KEY<TAB>text", with \\n for line
breaks and \\\\ for a backslash), and generates src/Text/LocIDs.h: which
text ID names each class, trait and spell (the ToStringID / DescriptionID
functions of ClassType.cs, TraitType.cs and SpellType.cs).

    python3 tools/convert_loc.py ref/RogueLegacy1 assets src
"""
import os
import re
import sys
import xml.etree.ElementTree as ET

LANGS = {'': 'en', 'fr': 'fr', 'de': 'de', 'es': 'es', 'pl': 'pl', 'pt': 'pt', 'ru': 'ru', 'zh': 'zh'}


def convert_resx(src, dst):
    root = ET.parse(src).getroot()
    n = 0
    with open(dst, 'w', encoding='utf-8') as f:
        for data in root.findall('data'):
            value = data.find('value')
            if value is None or value.text is None:
                continue
            text = (value.text.replace('\\', '\\\\').replace('\r', '')
                    .replace('\n', '\\n').replace('\t', ' '))
            f.write('%s\t%s\n' % (data.get('name'), text))
            n += 1
    return n


def function_body(text, start):
    i = text.index('{', start)
    depth = 0
    for j in range(i, len(text)):
        if text[j] == '{':
            depth += 1
        elif text[j] == '}':
            depth -= 1
            if depth == 0:
                return text[i:j]
    return ''


def id_functions(path):
    """Parses 'public static string F(byte x[, bool isFemale])' switch tables."""
    text = open(path, encoding='utf-8-sig').read()
    text = re.sub(r'//[^\n]*', '', text)
    funcs = []
    for m in re.finditer(r'public\s+static\s+string\s+(\w+)\s*\(\s*byte\s+\w+\s*(,\s*bool\s+isFemale[^)]*)?\)', text):
        body = function_body(text, m.end())
        entries, pending = [], []
        for tok in re.finditer(r'case\s*\(?\s*(?:\w+\.)?(\w+)\s*\)?\s*:|return\s+([^;]+);', body):
            if tok.group(1):
                pending.append(tok.group(1))
                continue
            expr = tok.group(2).strip()
            ternary = re.match(r'(!?)\s*isFemale\s*\?\s*"([^"]*)"\s*:\s*"([^"]*)"', expr)
            if ternary:
                neg, a, b = ternary.groups()
                male, female = (a, b) if neg else (b, a)
            else:
                s = re.match(r'"([^"]*)"', expr)
                if not s:
                    pending = []
                    continue
                male = female = s.group(1)
            for p in pending:
                entries.append((p, male, female))
            pending = []
        funcs.append((m.group(1), bool(m.group(2)), entries))
    return funcs


def main():
    if len(sys.argv) != 4:
        print(__doc__)
        sys.exit(1)
    ref, assets, src_out = sys.argv[1:]
    res = os.path.join(ref, 'RogueCastle', 'Resources')
    os.makedirs(os.path.join(assets, 'lang'), exist_ok=True)
    for suffix, code in LANGS.items():
        name = 'LocStrings%s.resx' % ('.' + suffix if suffix else '')
        path = os.path.join(res, name)
        if os.path.exists(path):
            n = convert_resx(path, os.path.join(assets, 'lang', code + '.txt'))
            print('lang %s: %d texts' % (code, n))

    src = os.path.join(ref, 'RogueCastle', 'src', 'Types')
    out = ['// Generated by tools/convert_loc.py from ClassType.cs, TraitType.cs and',
           '// SpellType.cs -- DO NOT EDIT. Text IDs for Text::Loc::Get.',
           '#pragma once',
           '#include "../RogueCastle/Types/ClassType.h"',
           '#include "../RogueCastle/Types/SpellType.h"',
           '#include "../RogueCastle/Types/TraitType.h"',
           '', 'namespace LocIDs', '{']
    for cls in ('ClassType', 'TraitType', 'SpellType'):
        for fname, female, entries in id_functions(os.path.join(src, cls + '.cs')):
            if not entries:
                continue
            out.append('    // %s.%s' % (cls, fname))
            out.append('    inline const char *%s_%s(int v%s)' % (cls, fname, ', bool isFemale = false' if female else ''))
            out.append('    {')
            if female:
                out.append('        (void) isFemale;')
            out.append('        switch (v)')
            out.append('        {')
            for const, male, fem in entries:
                if female and male != fem:
                    out.append('        case %s::%s: return isFemale ? "%s" : "%s";' % (cls, const, fem, male))
                else:
                    out.append('        case %s::%s: return "%s";' % (cls, const, male))
            out.append('        default: return "";')
            out.append('        }')
            out.append('    }')
            print('ids %s.%s: %d entries' % (cls, fname, len(entries)))
    out += ['}', '']
    path = os.path.join(src_out, 'Text', 'LocIDs.h')
    with open(path, 'w') as f:
        f.write('\n'.join(out))
    print('wrote', path)


if __name__ == '__main__':
    main()
