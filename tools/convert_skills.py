#!/usr/bin/env python3
"""Generates src/RogueCastle/Skills/SkillData.h from the reference C# source:
the SkillType enum (Types/SkillType.cs), each skill's numbers
(SkillBuilder.BuildSkill) and the manor grid (SkillSystem.cs).

    python3 tools/convert_skills.py ref/RogueLegacy1 src
"""
import os
import re
import sys


def main():
    if len(sys.argv) != 3:
        print(__doc__)
        sys.exit(1)
    ref, out_dir = sys.argv[1], sys.argv[2]
    src = os.path.join(ref, 'RogueCastle', 'src')

    # enum SkillType { Null = 0, Filler, Health_Up, ... }
    text = open(os.path.join(src, 'Types', 'SkillType.cs'), encoding='utf-8-sig').read()
    body = text[text.index('enum SkillType'):]
    body = body[body.index('{') + 1:body.index('}')]
    body = re.sub(r'//[^\n]*', '', body)
    names, value = [], -1
    for item in body.split(','):
        item = item.strip()
        if not item:
            continue
        if '=' in item:
            name, v = [s.strip() for s in item.split('=')]
            value = int(v)
        else:
            name = item
            value += 1
        names.append((name, value))

    # SkillBuilder.BuildSkill: case (SkillType.X): trait.Field = value; ...
    text = open(os.path.join(src, 'SkillBuilder.cs'), encoding='utf-8-sig').read()
    text = text[:text.index('GetSkillLinker')]
    text = re.sub(r'//[^\n]*', '', text)
    skills = {}
    for m in re.finditer(r'case\s*\(\s*SkillType\.(\w+)\s*\)\s*:(.*?)break;', text, re.S):
        fields = dict(re.findall(r'trait\.(\w+)\s*=\s*([^;]+);', m.group(2)))
        skills[m.group(1)] = fields

    # SkillSystem: m_skillTypeArray[10,10] and m_manorPieceArray[10,10]
    text = open(os.path.join(src, 'SkillSystem.cs'), encoding='utf-8-sig').read()
    text = re.sub(r'//[^\n]*', '', text)
    def grid(var, cell):
        block = text[text.index(var):]
        block = block[block.index('{') + 1:]
        rows = re.findall(r'\{([^{}]*)\}', block[:block.index('};')])
        return [re.findall(cell, r) for r in rows]
    type_grid = grid('m_skillTypeArray', r'SkillType\.(\w+)')
    piece_grid = grid('m_manorPieceArray', r'-?\d+')
    def vec_grid(var):
        block = text[text.index(var):]
        block = block[block.index('{') + 1:]
        rows = re.findall(r'\{((?:[^{}]|\([^()]*\))*)\}', block[:block.index('};')])
        return [re.findall(r'new\s+Vector2\s*\(\s*([-\d.]+)\s*,\s*([-\d.]+)\s*\)', r) for r in rows]
    pos_grid = vec_grid('m_skillPositionArray')
    builder = open(os.path.join(src, 'SkillBuilder.cs'), encoding='utf-8-sig').read()
    builder = re.sub(r'//[^\n]*', '', builder[builder.index('GetSkillLinker'):])
    links = []
    for m in re.finditer(r'if\s*\(\s*xIndex\s*==\s*(\d+)\s*&&\s*yIndex\s*==\s*(\d+)\s*\)\s*\{(.*?)\}', builder, re.S):
        d = dict((k, v) for k, v in re.findall(r'link\.(\w+)Link\s*=\s*new\s+Vector2\s*\(\s*(-?\d+\s*,\s*-?\d+)\s*\)', m.group(3)))
        def xy(k):
            v = d.get(k, '-1, -1').replace(' ', '').split(',')
            return v[0], v[1]
        links.append((m.group(1), m.group(2), xy('Top'), xy('Bottom'), xy('Left'), xy('Right')))
    starting = re.search(r'StartingTrait\s*=\s*SkillType\.(\w+)', text).group(1)
    level_cost = re.search(r'SKILL_LEVEL_COST_INCREASE\s*=\s*(\d+)',
                           open(os.path.join(src, 'EVs', 'GameEV.cs'), encoding='utf-8-sig').read()).group(1)

    def num(v, default='0'):
        if v is None:
            return default
        v = v.strip()
        return re.sub(r'(\d)f\b', r'\1', v)

    def string(v):
        return v.strip() if v is not None and v.strip().startswith('"') else '""'

    out = ['// Generated by tools/convert_skills.py from SkillType.cs, SkillBuilder.cs',
           '// and SkillSystem.cs -- DO NOT EDIT.',
           '#pragma once',
           '#include <cstdint>',
           '',
           'namespace Skills',
           '{',
           '    // Types/SkillType.cs',
           '    enum class SkillType : uint8_t',
           '    {']
    for name, value in names:
        out.append('        %s = %d,' % (name, value))
    out += ['    };', '',
            '    struct SkillInfo',
            '    {',
            '        SkillType type;',
            '        const char *name;        // English name (NameLocID for the translations)',
            '        const char *nameLocID;',
            '        const char *descLocID;',
            '        const char *iconName;    // ...Locked_Sprite; "Locked" -> "" / "Max" by level',
            '        const char *unit;        // UnitOfMeasurement',
            '        float perLevelModifier;  // ModifierAmount = CurrentLevel * PerLevelModifier',
            '        int baseCost;',
            '        int appreciation;        // extra cost per level of this skill',
            '        int maxLevel;',
            '        bool displayStat;        // shows Current/Upgrade amounts',
            '    };', '',
            '    // Skills from Health_Up to SuperSecret (SkillSystem.Initialize: 2 .. DIVIDER-1)',
            '    inline const SkillInfo SKILLS[] =',
            '    {']
    divider = dict(names)['DIVIDER']
    count = 0
    for name, value in names:
        if value < 2 or value >= divider:
            continue
        f = skills.get(name, {})
        out.append('        { SkillType::%s, %s, %s, %s, %s, %s, %sf, %s, %s, %s, %s },' % (
            name, string(f.get('Name')), string(f.get('NameLocID')), string(f.get('DescLocID')),
            string(f.get('IconName')), string(f.get('UnitOfMeasurement')),
            num(f.get('PerLevelModifier')).rstrip('f') if '.' in num(f.get('PerLevelModifier')) else num(f.get('PerLevelModifier')) + '.0',
            num(f.get('BaseCost')), num(f.get('Appreciation')), num(f.get('MaxLevel')),
            'true' if f.get('DisplayStat', 'false').strip() == 'true' else 'false'))
        count += 1
    out += ['    };',
            '    constexpr int SKILL_COUNT = %d;' % count, '',
            '    // The manor: skill at [row][column] (SkillSystem.m_skillTypeArray)',
            '    constexpr int GRID_ROWS = %d, GRID_COLS = %d;' % (len(type_grid), len(type_grid[0])),
            '    inline const SkillType SKILL_GRID[GRID_ROWS][GRID_COLS] =',
            '    {']
    for row in type_grid:
        out.append('        { %s },' % ', '.join('SkillType::' + c for c in row))
    out += ['    };', '',
            '    // Manor building piece shown by each skill (m_manorPieceArray, -1 = none)',
            '    inline const int8_t MANOR_PIECE[GRID_ROWS][GRID_COLS] =',
            '    {']
    for row in piece_grid:
        out.append('        { %s },' % ', '.join(row))
    out += ['    };', '',
            '    // Where each skill icon sits on the manor screen, in 1320x720 game',
            '    // coordinates (SkillSystem.m_skillPositionArray, [row][column])',
            '    struct IconPos { float x, y; };',
            '    inline const IconPos SKILL_POSITION[GRID_ROWS][GRID_COLS] =',
            '    {']
    for row in pos_grid:
        out.append('        { %s },' % ', '.join('{ %s, %s }' % (x, y) for x, y in row))
    out += ['    };', '',
            '    // Cursor moves on the manor screen (SkillBuilder.GetSkillLinker):',
            '    // from grid cell (x = column, y = row), the cell reached by up, down,',
            '    // left and right; -1 = no move',
            '    struct SkillLink { int x, y, upX, upY, downX, downY, leftX, leftY, rightX, rightY; };',
            '    inline const SkillLink SKILL_LINKS[] =',
            '    {']
    for x, y, t, b, l, r in links:
        out.append('        { %s, %s, %s, %s, %s, %s, %s, %s, %s, %s },' % (x, y, t[0], t[1], b[0], b[1], l[0], l[1], r[0], r[1]))
    out += ['    };',
            '    constexpr int SKILL_LINK_COUNT = %d;' % len(links)]
    out += ['',
            '    constexpr SkillType STARTING_SKILL = SkillType::%s; // visible on a new game' % starting,
            '    constexpr int SKILL_LEVEL_COST_INCREASE = %s;    // GameEV: cost added per player level' % level_cost,
            '}', '']
    path = os.path.join(out_dir, 'RogueCastle', 'Skills', 'SkillData.h')
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, 'w') as f:
        f.write('\n'.join(out))
    print('wrote %s (%d skills, %dx%d grid)' % (path, count, len(type_grid), len(type_grid[0])))


if __name__ == '__main__':
    main()
