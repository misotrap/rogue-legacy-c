#!/usr/bin/env python3
"""Generates src/RogueCastle/Equipment/EquipmentData.h from the reference
C# source: the type constants (Types/EquipmentType.cs), the 75 pieces of
equipment and the rune costs (EquipmentSystem.cs).

    python3 tools/convert_equipment.py ref/RogueLegacy1 src
"""
import os
import re
import sys


def split_args(s):
    """Splits on commas that are not inside parentheses."""
    out, depth, cur = [], 0, ''
    for ch in s:
        if ch == '(':
            depth += 1
        elif ch == ')':
            depth -= 1
        if ch == ',' and depth == 0:
            out.append(cur.strip())
            cur = ''
        else:
            cur += ch
    if cur.strip():
        out.append(cur.strip())
    return out


def main():
    if len(sys.argv) != 3:
        print(__doc__)
        sys.exit(1)
    ref, out_dir = sys.argv[1], sys.argv[2]
    src = os.path.join(ref, 'RogueCastle', 'src')

    # public class X { public const int A = 0; ... } in EquipmentType.cs
    text = open(os.path.join(src, 'Types', 'EquipmentType.cs'), encoding='utf-8-sig').read()
    text = re.sub(r'//[^\n]*', '', text)
    classes = []
    for m in re.finditer(r'class\s+(\w+)\s*\{', text):
        start = m.end()
        consts = []
        for c in re.finditer(r'public\s+const\s+int\s+(\w+)\s*=\s*(-?\d+)\s*;', text[start:]):
            # stop at the next class
            if re.search(r'class\s+\w+\s*\{', text[start:start + c.start()]):
                break
            consts.append((c.group(1), c.group(2)))
        if consts:
            classes.append((m.group(1), consts))

    # EquipmentSystem.cs
    text = open(os.path.join(src, 'EquipmentSystem.cs'), encoding='utf-8-sig').read()
    text = re.sub(r'//[^\n]*', '', text)
    ability_base = re.search(r'AbilityCostBase\s*=\s*(\d+)', text).group(1)
    ability_mod = re.search(r'AbilityCostMod\s*=\s*(\d+)', text).group(1)
    ability_costs = re.findall(r'm_abilityCostArray\[EquipmentCategoryType\.(\w+)\]\[EquipmentAbilityType\.(\w+)\]\s*=\s*(\w+)', text)
    init = text[text.index('void InitializeEquipmentData'):]
    init = init[:init.index('private void CreateEquipmentData')]
    items = []
    for m in re.finditer(r'CreateEquipmentData\((.*?)\);', init, re.S):
        a = split_args(m.group(1))
        secondary = []
        for v in a[13:]:
            mm = re.match(r'new\s+Vector2\(\s*EquipmentSecondaryDataType\.(\w+)\s*,\s*([-\d.]+)f?\s*\)', v)
            if mm:
                secondary.append((mm.group(1), mm.group(2)))
        def colour(v):
            mm = re.match(r'new\s+Color\(\s*(\d+)\s*,\s*(\d+)\s*,\s*(\d+)\s*\)', v)
            r, g, b = (min(255, int(x)) for x in mm.groups())
            return '0xFF%02X%02X%02Xu' % (r, g, b)
        items.append({
            'category': a[0].split('.')[-1], 'level': a[1], 'chest': a[2], 'index': a[3], 'cost': a[4],
            'weight': a[5], 'health': a[6], 'damage': a[7], 'armor': a[8], 'mana': a[9], 'magic': a[10],
            'colour1': colour(a[11]), 'colour2': colour(a[12]), 'secondary': secondary,
        })

    out = ['// Generated by tools/convert_equipment.py from Types/EquipmentType.cs and',
           '// EquipmentSystem.cs -- DO NOT EDIT.',
           '#pragma once',
           '#include <cstdint>', '']
    for name, consts in classes:
        out.append('// C# class %s' % name)
        out.append('namespace %s' % name)
        out.append('{')
        for k, v in consts:
            out.append('    constexpr int %s = %s;' % (k, v))
        out.append('}')
        out.append('')
    out += ['namespace Equipment',
            '{',
            '    struct SecondaryAttribute',
            '    {',
            '        int type;     // EquipmentSecondaryDataType::',
            '        float amount;',
            '    };', '',
            '    // EquipmentData, one per [category][base type]',
            '    struct ItemData',
            '    {',
            '        int category, index;          // EquipmentCategoryType::, EquipmentBaseType::',
            '        int levelRequirement;         // chest level needed for its blueprint to drop',
            '        int chestColourRequirement;   // ChestType needed (0 brown .. 3 gold)',
            '        int cost, weight;',
            '        int bonusHealth, bonusDamage, bonusArmor, bonusMana, bonusMagic;',
            '        uint32_t firstColour, secondColour; // 0xAARRGGBB tints of the armour sprites',
            '        int numSecondary;',
            '        SecondaryAttribute secondary[3];',
            '    };', '',
            '    inline const ItemData ITEMS[] =',
            '    {']
    for it in items:
        sec = ', '.join('{ EquipmentSecondaryDataType::%s, %sf }' % (t, v if '.' in v else v + '.0') for t, v in it['secondary'])
        out.append('        { EquipmentCategoryType::%s, %s, %s, %s, %s, %s, %s, %s, %s, %s, %s, %s, %s, %d, { %s } },' % (
            it['category'], it['index'], it['level'], it['chest'], it['cost'], it['weight'], it['health'], it['damage'],
            it['armor'], it['mana'], it['magic'], it['colour1'], it['colour2'], len(it['secondary']), sec))
    out += ['    };',
            '    constexpr int ITEM_COUNT = %d;' % len(items), '',
            '    // Runes (EquipmentSystem.InitializeAbilityCosts / GetAbilityCost):',
            '    // cost = base cost of the rune + runes bought so far * ABILITY_COST_MOD',
            '    constexpr int ABILITY_COST_BASE = %s;' % ability_base,
            '    constexpr int ABILITY_COST_MOD = %s;' % ability_mod,
            '    struct RuneCost { int category, ability, cost; };',
            '    inline const RuneCost RUNE_COSTS[] =',
            '    {']
    for cat, ab, val in ability_costs:
        out.append('        { EquipmentCategoryType::%s, EquipmentAbilityType::%s, %s },' % (cat, ab, 'ABILITY_COST_BASE' if val == 'AbilityCostBase' else val))
    out += ['    };',
            '    constexpr int RUNE_COST_COUNT = %d;' % len(ability_costs),
            '}', '']
    path = os.path.join(out_dir, 'RogueCastle', 'Equipment', 'EquipmentData.h')
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, 'w') as f:
        f.write('\n'.join(out))
    print('wrote %s (%d items, %d rune costs, %d type classes)' % (path, len(items), len(ability_costs), len(classes)))


if __name__ == '__main__':
    main()
