#!/usr/bin/env python3
# EnemyEV.cs "<X>_Name" + "<X>_Name_locID" -> src/RogueCastle/Screens/EnemyNames.h
# (English enemy name -> its LOC_ID, for the pause screen plates)
import re, sys
src = open(sys.argv[1] if len(sys.argv) > 1 else 'ref/RogueLegacy1/RogueCastle/src/EVs/EnemyEV.cs', encoding='utf-8-sig').read()
names = dict(re.findall(r'const string (\w+)_Name = "([^"]*)"', src))
locs = dict(re.findall(r'const string (\w+)_Name_locID = "([^"]*)"', src))
pairs, seen = [], set()
for k, n in names.items():
    if k in locs and n not in seen:
        seen.add(n); pairs.append((n, locs[k]))
out = ['// Generated by tools/convert_enemy_names.py from EnemyEV.cs: do not edit.',
       '#pragma once', '', 'namespace RogueCastle', '{',
       '\tstruct EnemyNameLoc { const char *name, *locID; };',
       '\tconst EnemyNameLoc ENEMY_NAMES[] = {']
out += ['\t\t{ "%s", "%s" },' % p for p in pairs]
out += ['\t};', '}', '']
open('src/RogueCastle/Screens/EnemyNames.h', 'w').write('\n'.join(out))
print(len(pairs), 'names')
